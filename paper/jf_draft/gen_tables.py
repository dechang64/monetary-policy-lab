def stars(p):
    return "$^{***}$" if p < .01 else "$^{**}$" if p < .05 else "$^{*}$" if p < .1 else ""


def _p(p):
    if p < .001:
        return "$<$ .001"
    return f"{p:.3f}".lstrip("0")


def coef(v, prec=3):
    s = f"{v['beta']:+.{prec}f}"
    se = f"({v['se']:.{prec}f})"
    return f"{s}{stars(v['p'])} & {se}"


